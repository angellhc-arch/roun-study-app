const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(require('node:path').join(__dirname, '../roun_study_app.html'), 'utf8');
const names = ['getV2PlanReward','getV2PlannedCount','getV2CompletedCount','isV2Weekend','getV2UnitRewardForDate','getV2RewardCompletedCount','isV2NormalPlan','isV2FullyComplete','getV2ChallengeBonus','getV2WeekendPremium','getV2WeekendPremiumText','getV2PlanCompletionEstimate','getV2PlanCompletionBreakdown','getV2PlanEstimateDetail','getV2StreakMilestoneReward','calcV2LiveReward'];
const context = vm.createContext({getV2HabitReward:()=>({total:1500}),calcV2Streak:()=>0});
vm.runInContext(names.map(name=>{const start=html.indexOf('function '+name+'(');return html.slice(start,html.indexOf('\n}',start)+2);}).join('\n'),context);
const day = (createdAt,count=5,categoryKey='study')=>({items:[{createdAt,plannedCount:count,completedCount:0,categoryKey}]});
assert.equal(context.getV2PlanReward(day('2026-09-10T14:59:59Z'),'2026-09-11'),2000);
assert.equal(context.getV2PlanReward(day('2026-09-10T15:00:00Z'),'2026-09-11'),500);
assert.equal(context.getV2PlanReward(day('2026-09-11T02:59:59Z'),'2026-09-11'),500);
assert.equal(context.getV2PlanReward(day('2026-09-11T03:00:00Z'),'2026-09-11'),0);
assert.equal(context.getV2PlanReward(day('2026-09-12T00:00:00Z'),'2026-09-11'),0);
assert.equal(context.getV2PlanReward(day('2026-09-10T00:00:00Z',4),'2026-09-11'),0);
assert.equal(context.getV2PlanReward(day('2026-09-11T00:00:00Z'),'2026-09-12'),2000);
assert.equal(context.getV2PlanCompletionEstimate(day('2026-09-10T00:00:00Z'),'2026-09-11'),5750);
assert.equal(context.getV2PlanCompletionEstimate(day('2026-09-10T00:00:00Z',4),'2026-09-11'),2000);
assert.equal(context.getV2PlanCompletionEstimate(day('2026-09-10T00:00:00Z',5,'exercise'),'2026-09-11'),3500);
assert.equal(context.getV2PlanCompletionEstimate(day('2026-09-11T00:00:00Z',13),'2026-09-12'),22000);
assert.equal(context.getV2PlanCompletionEstimate({...day('2026-09-10T00:00:00Z'),isRestDay:true},'2026-09-11'),0);
console.log('PASS: KST boundaries, minimum plans, weekends, completion estimates, exercise cap, rest days');

const edited = day('2026-09-10T00:00:00Z');
edited.planUpdatedAt = '2026-09-11T02:59:59Z';
assert.equal(context.getV2PlanReward(edited, '2026-09-11'), 500);
edited.planUpdatedAt = '2026-09-11T03:00:00Z';
assert.equal(context.getV2PlanReward(edited, '2026-09-11'), 0);
edited.planUpdatedAt = '2026-09-10T14:59:59Z';
edited.updatedAt = '2026-09-11T04:00:00Z';
assert.equal(context.getV2PlanReward(edited, '2026-09-11'), 2000);
const legacy = day('2026-09-10T00:00:00Z');
legacy.items.push({...legacy.items[0], createdAt:'2026-09-11T03:00:00Z'});
assert.equal(context.getV2PlanReward(legacy, '2026-09-11'), 0);
console.log('PASS: last plan edit takes precedence; completion checks preserve planning reward');

const estimate = context.getV2PlanCompletionBreakdown(day('2026-09-10T00:00:00Z'), '2026-09-11');
assert.equal(estimate.completedReward, 2500);
assert.equal(estimate.fullBonus, 1250);
assert.equal(estimate.total, 5750);
assert.match(context.getV2PlanEstimateDetail(estimate), /완료보상 50% \+1,250원/);
const completed = day('2026-09-10T00:00:00Z');
completed.items[0].completedCount = 5;
assert.equal(context.calcV2LiveReward(completed, {}, '2026-09-11').total - 1500, estimate.total);
console.log('PASS: completion estimate includes 50% exactly once and matches actual payout');
